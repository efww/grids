def plot_update(name: str, b: dict):
    d = pdir(name)
    dd = _plot_dec(name)
    if b.get("reset"):
        dd = {}
    for k in ("room", "irp"):
        if b.get(k):
            dd[k] = [float(b[k][0]), float(b[k][1])]
    if b.get("scale_n"):                            # paper scale 1:N
        dd["m_per_pt"] = float(b["scale_n"]) * 25.4 / 72 / 1000
    if b.get("route_edit"):                          # {rid, poly}: a route dragged on the plot
        dd.setdefault("routes_edit", {})[b["route_edit"]["rid"]] = [[float(x), float(y)] for x, y in b["route_edit"]["poly"]]
    if b.get("jb_move"):                             # STEP 7: {jbs: [JB no], slot: slot id}
        mv = dd.setdefault("jb_moves", {})
        for j in b["jb_move"]["jbs"]:
            mv[str(j)] = str(b["jb_move"]["slot"])
    if b.get("jb_reset"):
        for j in (b["jb_reset"] if isinstance(b["jb_reset"], list) else [b["jb_reset"]]):
            (dd.get("jb_moves") or {}).pop(str(j), None)
    if b.get("tray_size"):                           # STEP 8: {seg, cls, w, n}
        t = b["tray_size"]
        dd.setdefault("tray_size", {}).setdefault(str(t["seg"]), {})[str(t["cls"])] = [int(t["w"]), max(1, int(t["n"]))]
    if b.get("tray_reset"):
        (dd.get("tray_size") or {}).pop(str(b["tray_reset"]), None)
    if b.get("route_reset"):
        (dd.get("routes_edit") or {}).pop(b["route_reset"], None)
    if b.get("rack_add"):                            # polyline drawn on the plot, pt
        dd.setdefault("racks_add", []).append([[float(x), float(y)] for x, y in b["rack_add"]])
    if b.get("rack_del") is not None:
        dd["racks_add"] = [r for i, r in enumerate(dd.get("racks_add", [])) if i != int(b["rack_del"])]
    if b.get("rack_toggle") is not None:             # switch an auto-detected rack off / on
        off = set(dd.get("racks_off", []))
        off ^= {int(b["rack_toggle"])}
        dd["racks_off"] = sorted(off)
    if b.get("confirm"):
        dd.setdefault("confirmed", [])
        if b["confirm"] not in dd["confirmed"]:
            dd["confirmed"].append(b["confirm"])
    (d / "plot_decisions.json").write_text(json.dumps(dd, ensure_ascii=False, indent=1), encoding="utf-8")


