def start_extract(name: str):
    m = meta(name)
    pdf = m.get("files", {}).get("pdf")
    if not pdf:
        raise ValueError("P&ID PDF를 먼저 올려 주세요")
    protect.require_pdf(pdir(name) / "input" / pdf, "다시 추출하려면 도면을 직접 읽어야 하는데 P&ID PDF에 보안이 걸려 있는데",
                        "P&ID 파일을 선택해 주시면 올린 뒤 바로 추출합니다")
    with LOCK:
        if JOBS.get(name, {}).get("state") == "running":
            return
        JOBS[name] = {"state": "running", "page": 0, "total": 0, "symbols": 0, "started": time.time(), "msg": "레전드 학습"}

    def work():
        try:
            def prog(p, n, k):
                j = JOBS[name]
                j.update(page=p, total=n, symbols=j["symbols"] + k, msg=f"심볼 인식 {p}/{n} 페이지")
            d = pdir(name)
            run_extract(d / "input" / pdf, d / "extract.json", progress=prog)
            CACHE.pop(name, None)
            shutil.rmtree(d / "cache", ignore_errors=True)
            (d / "cache").mkdir(exist_ok=True)
            m2 = meta(name)
            m2["extracted"] = time.strftime("%Y-%m-%d %H:%M")
            save_meta(name, m2)
            JOBS[name].update(msg="도면 페이지 이미지 저장 (보안이 다시 걸려도 화면에 쓰기 위해)")
            cache_pages(name, wait=True)
            JOBS[name].update(state="done", msg="완료", elapsed=round(time.time() - JOBS[name]["started"]))
        except Exception as e:  # report to the UI
            JOBS[name].update(state="error", msg=str(e), trace=traceback.format_exc())

    threading.Thread(target=work, daemon=True).start()


def cache_pages(name: str, wait: bool = False):
    """Save page images/positions while the P&ID is readable (background)."""
    key = name + ":raster"
    if JOBS.get(key, {}).get("state") == "running":
        return
    d = pdir(name)
    pdf = d / "input" / meta(name)["files"]["pdf"]
    if protect.pdf_locked(pdf):
        return
    JOBS[key] = {"state": "running", "page": 0, "total": 0, "msg": "도면 페이지 이미지 저장 중"}

    def work():
        try:
            pagecache.build(pdf, d, progress=lambda i, n: JOBS[key].update(page=i, total=n,
                                                                         msg=f"도면 페이지 이미지 저장 {i}/{n}"))
            JOBS[key].update(state="done", msg="완료")
            warm_pages(name, cards=True)
        except Exception as e:
            JOBS[key].update(state="error", msg=str(e))

    if wait:
        work()
    else:
        threading.Thread(target=work, daemon=True).start()


