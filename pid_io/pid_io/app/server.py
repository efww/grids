def project_state(name: str):
    m = meta(name)
    d = pdir(name)
    st = {"meta": m, "job": JOBS.get(name, {"state": "idle"}), "extracted": (d / "extract.json").exists(),
          "protected": protect.scan(d, {**m.get("files", {}), "concept": "concept.xlsx"}),
          "pages_cached": pagecache.ready(d), "cache_job": JOBS.get(name + ":raster", {"state": "idle"})}
    if m.get("files", {}).get("pdf") and not st["pages_cached"] and "pdf" not in st["protected"]:
        cache_pages(name)                          # PDF readable right now: save the page images
    ex = extracted(name)
    if ex:
        data, syms, notes = ex
        st["old_extract"] = "sheets" not in data
        by = {}
        for s in syms:
            by[s.cls] = by.get(s.cls, 0) + 1
        st["extract"] = {
            "pdf": data["pdf"], "pages": data["page_count"], "symbols": len(syms),
            "by_class": by,
            "esd_linked": 0, "dcs_linked": 0,
            "pumps": sum(1 for s in syms if s.func == "EQUIP:P"),
            "packages": sum(1 for s in syms if s.func == "EQUIP:PK"),
            "vendor_symbols": sum(1 for s in syms if s.vendor),
            "vendor_areas": sorted({s.vendor for s in syms if s.vendor}),
            "notes": sum(len(n.notes) for n in notes.values()),
            "train_sheets": [d for d, n in notes.items() if n.copies],
            "line_evidence": sum(1 for s in syms if s.role == "device" and s.line),
            "devices": sum(1 for s in syms if s.role == "device"),
        }
        try:                                       # drawn field instruments wired to DCS / ESD (current checklist)
            rows = computed(name)[4]
            drawn = [r for r in rows if r.origin == "도면인식" and r.io in ("AI", "AO", "DI", "DO", "TC/RTD")]
            st["extract"]["dcs_linked"] = len({r.src_tag or r.tag for r in drawn if r.system == "DCS"})
            st["extract"]["esd_linked"] = len({r.src_tag or r.tag for r in drawn if r.system == "ESD"})
        except Exception as e:                     # show the reason instead of a silent 0
            st["extract"]["dcs_linked"] = st["extract"]["esd_linked"] = None
            st["calc_error"] = str(e)
    if CACHE.get(name, {}).get("notice"):
        st["notice"] = CACHE[name]["notice"]
    return st


