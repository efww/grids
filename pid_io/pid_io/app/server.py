def _scan_fonts():
    dirs = [STATIC / "fonts", STATIC.parent.parent.parent / "fonts"]
    win = os.environ.get("WINDIR")
    if win:
        dirs.append(Path(win) / "Fonts")
    la = os.environ.get("LOCALAPPDATA")
    if la:
        dirs.append(Path(la) / "Microsoft" / "Windows" / "Fonts")
    found = {}
    for d in dirs:
        try:
            files = list(d.iterdir()) if d.exists() else []
        except OSError:
            continue
        for f in files:
            n = f.name.lower()
            if f.suffix.lower() not in (".ttf", ".otf", ".woff", ".woff2"):
                continue
            if "harmony" not in n and "하모니" not in f.name:
                continue
            stem = re.sub(r"[\s_\-]", "", f.stem).upper()
            if "LIGHT" in stem or stem.endswith("L"):
                w = "L"
            elif "MEDIUM" in stem or stem.endswith("M"):
                w = "M"
            elif "BOLD" in stem or stem.endswith("B"):
                w = "B"
            else:
                w = "R"
            found.setdefault(w, f)
    return found


FONTS = _scan_fonts()


def font_css() -> str:
    if not FONTS:
        return ""
    rules = []
    body = FONTS.get("L") or FONTS.get("R")
    if body:
        rules.append(f'@font-face{{font-family:"HDHarmonyApp";src:url(/font/{"L" if "L" in FONTS else "R"});font-weight:100 499}}')
    bold = FONTS.get("B") or FONTS.get("M")
    if bold:
        k = "B" if "B" in FONTS else "M"
        rules.append(f'@font-face{{font-family:"HDHarmonyApp";src:url(/font/{k});font-weight:500 900}}')
    return "\n".join(rules)


