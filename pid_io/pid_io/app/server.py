def review_view(name: str, q: dict):
    c = computed(name)
    if not c:
        return {"ready": False}
    data, syms, notes, con, rows, log = c
    items, counts, ev_counts, decided = [], {}, {}, []
    for r in rows:
        if r.kind == "function" or r.origin in ("스페어", "트레인복제", "대수복제"):
            continue
        text = "; ".join(x for x in r.inform if not x.startswith("사용자 판단"))
        tags = [label for key, label in REASONS if key in text]
        it = {"card": r.sid or (f"p{r.page}_{r.coord}" if r.page and r.coord else ""), "key": r.key,
              "tag": r.tag, "desc": r.desc, "system": r.system, "io": r.io, "status": r.status,
              "origin": r.origin, "dwg": r.dwg, "page": r.page, "coord": r.coord, "vendor": r.vendor_pkg,
              "inform": text, "basis": r.basis, "explain": explain(r.inform, r)}
        if r.decided:
            if "#" not in r.key:                 # qty copies follow their source row
                decided.append({**it, "decided": r.decided, "reasons": tags})
            continue
        if r.status == "확정" and not tags:
            continue
        if r.status != "확정" and not tags:
            tags = ["파생/가정 행"] if r.derived else ["도형 일치도 낮음"]
        it["reasons"] = tags
        it["evidence"] = all(t in EVIDENCE for t in tags)
        bucket = ev_counts if it["evidence"] else counts
        for t in tags:
            bucket[t] = bucket.get(t, 0) + 1
        items.append(it)
    dk = dec.load(pdir(name))["rows"]
    for k, e in dk.items():               # excluded rows are gone from `rows`: list them so they can be undone
        if e.get("action") == "exclude":
            tag, _, desc = k.partition("|")
            decided.append({"key": k, "tag": tag, "desc": desc, "decided": "인덱스에서 제외", "reasons": [],
                            "card": "", "system": "", "io": "", "dwg": "", "page": 0, "coord": "", "origin": ""})
    ov = overrides(name)["symbols"]
    by = {s.sid: s for s in syms}
    for sid, o in ov.items():               # tag-like text the user judged by hand
        if str(o.get("reason", "")).startswith("사용자 판단") and sid in by:
            s = by[sid]
            decided.append({"key": "", "sid": sid, "tag": f"{s.func}-{s.number}", "desc": "태그 모양 글자",
                            "decided": "계기 아님" if o["class"] == "NOT_A_TAG" else f"현장 계기로 인정 {o.get('tag', '')}",
                            "reasons": [], "card": sid, "system": "", "io": "", "dwg": s.dwg, "page": s.page,
                            "coord": f"{round(s.cx)},{round(s.cy)}", "origin": "도면인식"})
    for s in syms:
        if s.role == "candidate" and s.sid not in ov:
            counts["미인식 후보"] = counts.get("미인식 후보", 0) + 1
            items.append({"card": s.sid, "key": "", "sid": s.sid, "tag": f"{s.func}-{s.number}",
                          "desc": "규칙에 맞지 않은 태그 모양 글자", "system": "?", "io": "-",
                          "status": "불명", "origin": "도면인식", "dwg": s.dwg, "page": s.page,
                          "coord": f"{round(s.cx)},{round(s.cy)}", "vendor": s.vendor, "inform": "; ".join(s.notes),
                          "basis": "", "reasons": ["미인식 후보"], "evidence": False,
                          "explain": [{"k": "ask", "t": "태그처럼 생긴 글자인데 레전드 심볼 규칙에 맞지 않아 계기인지 알 수 "
                                                        "없습니다. 확대 이미지를 보고 계기면 '현장 계기로 인정', 라인번호·노트면 "
                                                        "'계기 아님'을 눌러 주세요."}]})
    view = q.get("view", ["todo"])[0]
    f = q.get("reason", [""])[0]
    if view == "decided":
        sel = decided
    else:
        sel = [i for i in items if i["evidence"] == (view == "evidence")]
    if f:
        sel = [i for i in sel if f in i["reasons"]]
    pages = sorted({(s.page, s.dwg, s.title) for s in syms if s.page})
    notes_list = [{"dwg": d, "text": t, "effect": e} for d, n in notes.items() for t, e in n.notes]
    return {"ready": True, "counts": counts, "evidence_counts": ev_counts, "view": view,
            "n_todo": sum(1 for i in items if not i["evidence"]), "n_evidence": sum(1 for i in items if i["evidence"]),
            "n_decided": len(decided), "items": sel[:600], "total": len(sel),
            "pages": [{"page": p, "dwg": d, "title": t} for p, d, t in pages],
            "page_size": data["page_size"], "notes": notes_list}


def row_decide(name: str, b: dict):
    """Apply a review decision to one or more rows (keys). Body:
    {keys, action: ok|exclude|edit|undo, edit: {...}} or {keys, text, preview}."""
    d = pdir(name)
    if b.get("sid"):                       # unrecognised tag-like text: not a tag / accept as field instrument
        f = d / "overrides.json"
        ov = ait.load(f, {"symbols": {}, "rules": []})
        if b.get("action") == "undo":
            ov["symbols"].pop(b["sid"], None)
        elif b.get("action") == "exclude":
            ov["symbols"][b["sid"]] = {"class": "NOT_A_TAG", "tag": "", "io": "-", "system": "-", "reason": "사용자 판단"}
        else:
            ov["symbols"][b["sid"]] = {"class": "FIELD", "tag": b.get("tag", ""), "io": None, "system": None,
                                       "reason": "사용자 판단: 현장 계기"}
        ait.save(f, ov)
        return {"ok": True}
    keys = [k for k in (b.get("keys") or []) if k]
    if not keys:
        raise ValueError("대상 행이 없습니다")
    if b.get("action") == "undo":
        dd = dec.load(d)
        for k in keys:
            dd["rows"].pop(k, None)
        dec.save(d, dd)
        return {"ok": True}
    if "text" in b:
        e = dec.parse(b["text"])
        via = "규칙"
        st = ai.load_settings(HOME)
        if not e.get("understood") and st["provider"] == "copilot_cli" and b.get("use_ai", True):
            c = computed(name)
            r = next((x for x in c[4] if x.key == keys[0]), None) if c else None
            prompt = dec.AI_PROMPT.format(tag=getattr(r, "tag", keys[0]), desc=getattr(r, "desc", ""),
                                          system=getattr(r, "system", ""), io=getattr(r, "io", ""),
                                          dwg=getattr(r, "dwg", ""), text=b["text"])
            e = dec.from_ai(ait.extract_json(ai.ask(st, prompt)), b["text"])
            via = "AI"
    else:
        e = {"action": b.get("action", "ok"), **(b.get("edit") or {})}
        if b.get("note"):
            e["note"] = b["note"]
    e.pop("understood", None)
    if b.get("preview"):
        return {"edit": e, "summary": dec.summary(e), "via": via if "text" in b else "선택"}
    dd = dec.load(d)
    for k in keys:
        dd["rows"][k] = e
    dec.save(d, dd)
    return {"ok": True, "summary": dec.summary(e), "count": len(keys)}


def warm_pages(name: str, cards: bool = False):
    """Render the review page images (and the review crops) in the background."""
    key = name + ":warm"
    if JOBS.get(key, {}).get("state") == "running":
        return
    JOBS[key] = {"state": "running"}

    def work():
        try:
            ex = extracted(name)
            for p in sorted({s.page for s in ex[1] if s.page}) if ex else []:
                page_png(name, p)
            if cards:
                for v in ("todo", "evidence"):
                    for it in review_view(name, {"view": [v]}).get("items", []):
                        if it.get("card"):
                            try:
                                card_png(name, it["card"])
                            except Exception:
                                pass
        except Exception:
            pass
        JOBS[key] = {"state": "done"}

    threading.Thread(target=work, daemon=True).start()


def page_png(name: str, page: int) -> Path:
    d = pdir(name)
    out = d / "cache" / f"page_{page}.png"
    if out.exists():
        return out
    m = meta(name)
    ex = extracted(name)
    if pagecache.has_page(d, page):
        boxes = [(s.cx, s.cy, s.radius * 1.15, tuple(int(c * 255) for c in COLORS.get(s.cls, (0.3, 0.3, 0.3))))
                 for s in (ex[1] if ex else []) if s.page == page and s.role != "equipment"]
        return pagecache.overview(d, page, out, boxes)
    protect.require_pdf(d / "input" / m["files"]["pdf"],
                        "이 페이지 전체 도면 이미지가 아직 저장되지 않았는데 P&ID PDF에 보안이 걸려 있는데")
    doc = fitz.open(d / "input" / m["files"]["pdf"])
    pg = doc[page - 1]
    inv = ~pg.rotation_matrix
    from ..boundary import find_regions, legend_width
    for rg in find_regions(pg, legend_width(doc)):
        sh = pg.new_shape()
        sh.draw_rect(rg.rect * inv)
        sh.finish(color=(0.49, 0.4, 0.8), width=3, dashes="[12 4 3 4] 0")
        sh.commit()
    for s in (ex[1] if ex else []):
        if s.page != page or s.role == "equipment":
            continue
        r = s.radius * 1.15
        sh = pg.new_shape()
        sh.draw_rect(fitz.Rect(s.cx - r, s.cy - r, s.cx + r, s.cy + r) * inv)
        sh.finish(color=COLORS.get(s.cls, (0.3, 0.3, 0.3)), width=1.8)
        sh.commit()
    pg.get_pixmap(dpi=60).save(out)
    return out


def card_png(name: str, key: str) -> Path:
    """Marked-up crop for one review item. key = symbol id, or 'p<page>_<x>,<y>'."""
    import hashlib
    from ..markup import crop
    d = pdir(name)
    out = d / "cache" / "cards" / (hashlib.md5(key.encode()).hexdigest()[:16] + ".png")
    if out.exists():
        return out
    out.parent.mkdir(parents=True, exist_ok=True)
    ex = extracted(name)
    sym = next((s for s in ex[1] if s.sid == key), None) if ex else None
    if sym:
        page, cx, cy, r = sym.page, sym.cx, sym.cy, sym.radius
    else:
        pg, xy = key[1:].split("_", 1)
        page, (cx, cy), r = int(pg), map(float, xy.split(",")), 18
    if pagecache.has_page(d, page):
        return pagecache.card(d, page, cx, cy, out, sym=sym, radius=r)
    c = CACHE.setdefault(name, {}).setdefault("regions", {})
    pdf = d / "input" / meta(name)["files"]["pdf"]
    protect.require_pdf(pdf, "이 항목의 확대 이미지가 아직 저장되지 않았는데 P&ID PDF에 보안이 걸려 있는데")
    if page not in c:
        from ..boundary import find_regions, legend_width
        doc = fitz.open(pdf)
        c[page] = find_regions(doc[page - 1], legend_width(doc))
    return crop(pdf, page, cx, cy, out, sym=sym, radius=r, regions=c[page])


