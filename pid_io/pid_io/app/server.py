def _stamp(name: str):
    d = pdir(name)
    st = []
    for f in ("concept.xlsx", "overrides.json", "decisions.json", "extract.json"):
        p = d / f
        st.append(p.stat().st_mtime_ns if p.exists() else 0)
    return tuple(st)


def computed(name: str):
    """Rows for the current checklist + decisions. Cached until one of the input files changes."""
    ex = extracted(name)
    if not ex:
        return None
    with CALC:
        c = CACHE.setdefault(name, {})
        key = _stamp(name)
        if c.get("rows_key") == key and "rows" in c:
            return c["rows"]
        data, syms, notes = ex
        con = concept(name)
        rows, log = compute(syms, notes, con, overrides=overrides(name))
        c["rows"], c["rows_key"] = (data, syms, notes, con, rows, log), key
        return c["rows"]


def overrides(name: str):
    o = ait.load(pdir(name) / "overrides.json", {"symbols": {}, "rules": []})
    o["decisions"] = dec.load(pdir(name))
    return o


