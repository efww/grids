def safe_name(name: str) -> str:
    name = re.sub(r"[\\\\/:*?\"<>|]+", "_", name).strip(" .")
    if not name:
        raise ValueError("프로젝트 이름이 비어 있습니다")
    return name[:80]


def pdir(name: str) -> Path:
    d = (HOME / safe_name(name)).resolve()
    if HOME not in d.parents:
        raise ValueError("bad project")
    return d


def meta(name: str) -> dict:
    f = pdir(name) / "project.json"
    return json.loads(f.read_text(encoding="utf-8")) if f.exists() else {}


def save_meta(name: str, m: dict):
    (pdir(name) / "project.json").write_text(json.dumps(m, ensure_ascii=False, indent=1), encoding="utf-8")


def create_project(name: str):
    d = pdir(name)
    if d.exists():
        raise ValueError("같은 이름의 프로젝트가 있습니다")
    for sub in ("input", "cache", "output"):
        (d / sub).mkdir(parents=True)
    shutil.copy(default_concept(), d / "concept.xlsx")
    save_meta(name, {"name": safe_name(name), "created": time.strftime("%Y-%m-%d %H:%M"),
                     "files": {}, "scenarios": []})


def default_concept() -> Path:
    """protocols/concept_default.xlsx is generated by code; if the label locked it, regenerate it."""
    f = PROTO / "concept_default.xlsx"
    if f.exists() and not is_locked(f):
        return f
    import runpy
    import sys
    old = os.environ.get("OUT")
    os.environ["OUT"] = str(f)
    try:
        sys.modules.pop("pid_io.make_concept_template", None)
        runpy.run_module("pid_io.make_concept_template", run_name="__main__")
    finally:
        if old is None:
            os.environ.pop("OUT", None)
        else:
            os.environ["OUT"] = old
    return f


def concept(name: str) -> Concept:
    c = CACHE.setdefault(name, {})
    if "concept" not in c:
        try:
            c["concept"] = Concept(pdir(name) / "concept.xlsx")       # labelled file: opened through Excel
        except DirectOpenError as e:                                   # Excel automation not available
            c["concept"] = _fallback_concept(name, e)
    return c["concept"]


def _fallback_concept(name: str, err) -> Concept:
    """Only when Excel cannot open the labelled checklist: default + inputs saved in concept_values.json."""
    con = Concept(default_concept())
    con.path = pdir(name) / "concept.xlsx"
    vals = protect.load_values(pdir(name))
    n = con.apply_values(vals) if vals else 0
    CACHE.setdefault(name, {})["notice"] = (
        f"체크리스트 파일을 Excel로 열지 못해 기본값{'과 저장해 둔 입력값(' + str(n) + '개)' if vals else ''}으로 계산하고 "
        f"있는데, 바꿨던 값이 맞는지 개념 체크리스트에서 확인해 주세요. (원인: {err})")
    return con


def extracted(name: str):
    c = CACHE.setdefault(name, {})
