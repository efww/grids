def _note_items(name: str):
    ex = extracted(name)
    out = {"B01": [], "B03": [], "C09": []}
    if not ex:
        return out
    d = dec.load(pdir(name))
    for dwg, pn in ex[2].items():
        if pn.copy_text or pn.train_range:
            n = len(pn.copies) + 1 if pn.copies else 1
            out["B01"].append({"dwg": dwg, "page": pn.page, "title": pn.title,
                               "text": pn.copy_text or f"PREFIXED BY TRAIN NUMBER {pn.train_range[0]}~{pn.train_range[1]}",
                               "effect": f"트레인 {n}개 (원본 + 복제 {len(pn.copies)})" if pn.copies else "태그 접두만 적용 (복제 없음)",
                               "q": "B01"})
        if pn.only_one:
            out["B03"].append({"dwg": dwg, "page": pn.page, "title": pn.title, "text": pn.only_one,
                               "qty": d["only_one"].get(dwg, ""), "q": "B03"})
        if pn.later:
            out["C09"].append({"dwg": dwg, "page": pn.page, "title": pn.title, "text": pn.later, "q": "C09"})
    return out


def _typical_view(con: Concept, typ: str):
    pts = []
    for p in con.points:
        if p.typical != typ:
            continue
        pts.append({"func": p.func, "suffix": p.suffix, "desc": p.desc, "system": con.system(p.system), "io": p.io,
                    "qty": con.qty(p.qty), "qty_id": p.qty if isinstance(p.qty, str) else "",
                    "cond": p.cond, "active": con.cond_ok(p.cond) and con.qty(p.qty) > 0})
    return pts


def concept_view(name: str):
    con = concept(name)
    groups = []
    for iid, it in con.items.items():
        if not groups or groups[-1]["title"] != it["group"]:
            groups.append({"title": it["group"], "items": []})
        row = {"id": iid, **{k: it[k] for k in ("name", "type", "value", "default", "choices",
                                                 "effect", "basis", "status", "status_note")}}
        if iid in LABELS:
            row["name"], row["effect"] = LABELS[iid]
        groups[-1]["items"].append(row)
    pk = []
    ex = extracted(name)
    seen = set()
    if ex:
        for s in ex[1]:
            if s.func == "EQUIP:PK":
                typ, conn, prow, src = con.package_typical(s.number)
                units = s.notes[0].split(":", 1)[1] if s.notes else ""
                pn = ex[2].get(s.dwg)
                pk.append({"tag": s.number, "dwg": s.dwg, "title": s.title, "units": units,
                           "conn": conn, "typical": typ, "source": src, "later": bool(pn and pn.later),
                           "qty": (prow or {}).get("qty") or max(1, len([u for u in units.split("/") if u]))})
                seen.add(s.number)
    for p in con.packages:
        if not any(p["tag"].startswith(t) for t in seen):
            pk.append({"tag": p["tag"], "dwg": p.get("dwg"), "title": p.get("name"), "units": "",
                       "conn": p.get("conn"), "typical": p.get("typical"), "source": "Package_Concept",
                       "qty": p.get("qty"), "later": False})
    typs = sorted({p.typical for p in con.points if p.typical.startswith(("MTR-", "PKG-"))})
    d = dec.load(pdir(name))
    return {"groups": groups, "packages": pk, "changed": len(con.changed()), "overlay_default": con.on("I03"),
            "notes": _note_items(name), "typicals": {t: _typical_view(con, t) for t in typs},
            "allowance": {k: int(d["allowance"].get(k, 0) or 0) for k in ("AI", "AO", "DI", "DO")}}


def note_png(name: str, page: int, which: str) -> bytes:
    """Crop of the drawing around the note that drives a checklist item (highlighted)."""
    m = meta(name)
    if pagecache.has_page(pdir(name), page):
        return pagecache.note(pdir(name), page, which)
    protect.require_pdf(pdir(name) / "input" / m["files"]["pdf"],
                        "노트 위치 이미지를 만들려면 도면이 필요한데 P&ID PDF에 보안이 걸려 있는데")
    doc = fitz.open(pdir(name) / "input" / m["files"]["pdf"])
    pg = doc[page - 1]
    hits = []
    for q in pagecache.NOTE_SEARCH.get(which, ()):
        hits += pg.search_for(q)
    if not hits:
        raise ValueError("도면에서 노트 위치를 찾지 못했습니다")
    r = fitz.Rect(hits[0])
    for h in hits[1:3]:
        if abs(h.y0 - r.y0) < 200:
            r |= h
    sh = pg.new_shape()
    for h in hits:
        sh.draw_rect(h + (-2, -2, 2, 2))
    sh.finish(color=(0.88, 0.12, 0.22), fill=(1, 0.85, 0.2), fill_opacity=0.35, width=1.2)
    sh.commit()
    clip = (r + (-330, -60, 330, 90)) & pg.rect
    return pg.get_pixmap(dpi=130, clip=clip).tobytes("png")


